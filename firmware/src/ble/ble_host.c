/**
 * @section Test if advertisement contains HID UUID
 * @param packet
 * @param size
 * @returns true if it does
 */
/* Forget one device: drop its LTK from the bonding db AND the "last connected" tag, so the next
   attempt is a genuine fresh pairing rather than another doomed re-encryption. */
/* Kept for the clear_bonds() config command (still an empty stub on the Pico path). NOT called
   automatically any more -- see hog_discovery_timeout() for why unilaterally dropping our key
   behind the user's back is harmful. */
/* Forget EVERY bond, plus the "last connected device" tag. This is what the config tool's
   "Clear bonds" button does.
   NOTE the warning the tool must show the user: this clears OUR side only. The remote still holds
   ITS key, so it may think it already knows us -- accept the link, refuse to re-pair and refuse to
   serve GATT. Re-pair the REMOTE too, or you get a half-bond deadlock. (We learned this the hard
   way: it broke other, working firmware on the same remote.) */
static void ble_clear_all_bonds(void){
    int deleted = 0;
    int max = le_device_db_max_count();
    for (int i = 0; i < max; i++){
        int addr_type = BD_ADDR_TYPE_UNKNOWN;
        bd_addr_t addr;
        sm_key_t irk;
        le_device_db_info(i, &addr_type, addr, irk);
        if (addr_type == BD_ADDR_TYPE_UNKNOWN) continue;
        le_device_db_remove(i);
        deleted++;
    }
    btstack_tlv_get_instance(&btstack_tlv_singleton_impl, &btstack_tlv_singleton_context);
    if (btstack_tlv_singleton_impl){
        btstack_tlv_singleton_impl->delete_tag(btstack_tlv_singleton_context, TLV_TAG_HOGD);
    }
    printf("   %d bond(s) cleared. NOTE: the REMOTE still holds its key -- re-pair it too.\n", deleted);
}

__attribute__((unused))
static void ble_forget_device(const bd_addr_t addr, bd_addr_type_t addr_type){
    // gap_delete_bonding() is the portable API. (This btstack has no
    // le_device_db_index_for_address.)
    gap_delete_bonding(addr_type, (uint8_t *) addr);
    printf("   bond for %s deleted\n", bd_addr_to_str((uint8_t *) addr));

    // also drop the "last connected device" tag, so the next boot scans instead of
    // going straight back to a device we just decided not to trust
    btstack_tlv_get_instance(&btstack_tlv_singleton_impl, &btstack_tlv_singleton_context);
    if (btstack_tlv_singleton_impl){
        btstack_tlv_singleton_impl->delete_tag(btstack_tlv_singleton_context, TLV_TAG_HOGD);
    }
}

static bool adv_event_contains_hid_service(const uint8_t * packet){
    const uint8_t * ad_data = gap_event_advertising_report_get_data(packet);
    uint8_t ad_len = gap_event_advertising_report_get_data_length(packet);
    return ad_data_contains_uuid16(ad_len, ad_data, ORG_BLUETOOTH_SERVICE_HUMAN_INTERFACE_DEVICE);
}

/* WHY THE LED USED TO BLINK FOR AGES BEFORE CONNECTING.
   The BTstack example scans FOREVER waiting for an advertisement that carries the HID service
   UUID. A real BLE remote only puts that UUID (and its name) in the occasional advert -- most
   of its packets are bare -- and when it is asleep it may never send one. So we sat there
   skipping the device over and over.

   The fix (from shiomachisoft/picow_ble_usb_hid_bridge, which stays connected):
     * give scanning a DEADLINE, and when it expires connect straight to the BONDED address.
       A direct connect wakes the remote; it does not need to advertise at all.
     * make the connection timeout short (3s, not 10s) so a failed attempt is retried quickly
       instead of leaving the LED blinking for ten seconds.
     * ALWAYS remove a timer before re-adding it -- btstack_run_loop_add_timer asserts if the
       timer is already queued, which is easy to hit when a scan restarts mid-reconnect. */
#define CONNECTION_TIMEOUT_MS 3000
#define SCAN_TIMEOUT_MS       5000
/* HID discovery had NO deadline: hids_client_connect() would return OK and then the peer would
   simply never answer, leaving the firmware fast-blinking in silence forever -- the exact symptom
   on hardware. The cause is a STALE BOND: we reconnect and "Re-encryption complete, success", but
   the remote no longer honours that key for its GATT database, so it accepts the link and then
   ignores every discovery request. It is not recoverable by waiting.
   So: give discovery a deadline, and when it expires DELETE THE BOND and pair fresh. Self-healing;
   no need to put the remote into pairing mode by hand. (Clearing the bonds by hand is exactly what
   made it work the first time.) */
#define HID_DISCOVERY_TIMEOUT_MS 6000

static void ble_forget_device(const bd_addr_t addr, bd_addr_type_t addr_type);

/**
 * HID discovery went quiet. The bond is not trusted by the peer -- drop it and pair fresh.
 */
static void hog_discovery_timeout(btstack_timer_source_t * ts){
    UNUSED(ts);
    if (app_state != W4_HID_CLIENT_CONNECTED) return;
    printf("!! HID discovery timed out -- the peer accepted the link but will not serve its GATT db.\n");
    printf("   This is almost always the REMOTE, not us: a BLE HID device serves its HID service\n");
    printf("   to ONE bonded host. If it is still paired to a TV/phone, put it into pairing mode.\n");

    // DO NOT delete the bond here.
    //
    // An earlier version did, and it made things worse: deleting OUR key while the remote keeps
    // ITS key leaves a HALF BOND. The remote then thinks it already knows us, so it accepts the
    // link, refuses to re-pair, and refuses to serve GATT -- a deadlock that no firmware can get
    // out of, and which breaks other (working) firmware on the same remote too. The fix has to
    // happen on the remote (re-pair it), not by quietly desyncing the keys behind the user's back.
    app_state = W4_TIMEOUT_THEN_SCAN;
    if (connection_handle != HCI_CON_HANDLE_INVALID) {
        gap_disconnect(connection_handle);   // the disconnect handler restarts the scan
    } else {
        hog_start_connect();   // NOT _scan: that would make us pairable again
    }
}

/**
 * Scanning found nothing in time -> stop guessing and connect to the device we already know.
 */
static void hog_scan_timeout(btstack_timer_source_t * ts){
    UNUSED(ts);
    if (app_state != W4_HID_DEVICE_FOUND) return;
    printf("Scan timeout - trying a direct connect to the bonded device...\n");
    gap_stop_scan();
    hog_start_connect();
}

/**
 * Start scanning
 */
static void hog_start_scan(void){
    printf("Scanning for LE HID devices (timeout %dms)...\n", SCAN_TIMEOUT_MS);
    app_state = W4_HID_DEVICE_FOUND;

    btstack_run_loop_remove_timer(&connection_timer);   // may still be queued from a reconnect
    btstack_run_loop_set_timer(&connection_timer, SCAN_TIMEOUT_MS);
    btstack_run_loop_set_timer_handler(&connection_timer, &hog_scan_timeout);
    btstack_run_loop_add_timer(&connection_timer);

    // Active scanning, 100% (scan interval = scan window) -- also requests
    // scan responses so we see names/UUIDs for the diagnostic log below.
    gap_set_scan_parameters(1,48,48);
    gap_start_scan();
}

/**
 * Handle timeout for outgoing connection
 * @param ts
 */
static void hog_connection_timeout(btstack_timer_source_t * ts){
    UNUSED(ts);
    printf("Connection timeout - back to scanning\n");
    gap_connect_cancel();
    hog_start_connect();   // NOT _scan: that would make us pairable again
}


/**
 * Connect to remote device but set timer for timeout
 */
static void hog_connect(void) {
    printf("Connecting to %s (timeout %dms)...\n", bd_addr_to_str(remote_device.addr), CONNECTION_TIMEOUT_MS);

    btstack_run_loop_remove_timer(&connection_timer);   // the scan timeout may still be armed
    btstack_run_loop_set_timer(&connection_timer, CONNECTION_TIMEOUT_MS);
    btstack_run_loop_set_timer_handler(&connection_timer, &hog_connection_timeout);
    btstack_run_loop_add_timer(&connection_timer);

    app_state = W4_CONNECTED;
    gap_connect(remote_device.addr, remote_device.addr_type);
}

/**
 * Handle timer event to trigger reconnect
 * @param ts
 */
static void hog_reconnect_timeout(btstack_timer_source_t * ts){
    UNUSED(ts);
    switch (app_state){
        case W4_TIMEOUT_THEN_RECONNECT:
            hog_connect();
            break;
        case W4_TIMEOUT_THEN_SCAN:
            // NOT hog_start_scan(): that would make us pairable again. Go through
            // hog_start_connect(), which reconnects to the KNOWN device, and only scans if a
            // pairing window is actually open.
            hog_start_connect();
            break;
        default:
            break;
    }
}

/**
 * Start connecting after boot up: connect to last used device if possible, start scan otherwise
 */
static void hog_start_connect(void){
    // check if we have a bonded device
    btstack_tlv_get_instance(&btstack_tlv_singleton_impl, &btstack_tlv_singleton_context);
    if (btstack_tlv_singleton_impl){
        int len = btstack_tlv_singleton_impl->get_tag(btstack_tlv_singleton_context, TLV_TAG_HOGD, (uint8_t *) &remote_device, sizeof(remote_device));
        if (len == sizeof(remote_device)){
            printf("Bonded, connect to device with %s address %s ...\n", remote_device.addr_type == 0 ? "public" : "random" , bd_addr_to_str(remote_device.addr));
            hog_connect();
            return;
        }
    }

    /* NO BOND -> we are pairable. This is first-time setup, and it is the ONLY time we go looking
       for a device we do not already know.
     *
     * The security question the owner asked was: "if the remote disconnects, is it open to anything
     * in the room?" The answer is NO -- and the reason is the branch ABOVE, not this one. Once a
     * device is bonded we ONLY ever reconnect to that device; a remote that is switched off or out
     * of range leaves the bond intact, so we sit there retrying it and will not touch anything else.
     *
     * An EARLIER version of this made a bond-less device sit idle and refuse to scan at all. That
     * bought no safety whatsoever (a device with no bond has nothing to protect) and it broke the
     * one thing that worked: a fresh remapper could never pair with anything, ever.
     *
     * So the rule is simply:
     *   bonded      -> reconnect to that device, and ONLY that device. Never pair with anything.
     *   not bonded  -> pairable (first-time setup, or right after "Pair new device"/"Clear bonds").
     */
    if (!pairing_mode) {
        printf("No bonded device -- looking for one to pair with (first-time setup).\n");
    }
    hog_start_scan();
}

/**
 * In case of error, disconnect and start scanning again
 */
static void handle_outgoing_connection_error(void){
    printf("Error occurred, disconnect and start over\n");
    gap_disconnect(connection_handle);
    hog_start_connect();   // NOT _scan: that would make us pairable again
}

/**
 * Handle GATT Client Events dependent on current state
 *
 * @param packet_type
 * @param channel
 * @param packet
 * @param size
 */
static void handle_gatt_client_event(uint8_t packet_type, uint16_t channel, uint8_t *packet, uint16_t size) {
    UNUSED(packet_type);
    UNUSED(channel);
    UNUSED(size);

    uint8_t status;

    if (hci_event_packet_get_type(packet) != HCI_EVENT_GATTSERVICE_META){
        return;
    }
    
    switch (hci_event_gattservice_meta_get_subevent_code(packet)){
        case GATTSERVICE_SUBEVENT_HID_SERVICE_CONNECTED:
            status = gattservice_subevent_hid_service_connected_get_status(packet);
            switch (status){
                case ERROR_CODE_SUCCESS:
                    // discovery succeeded -- disarm the deadline, or it would delete a good bond
                    btstack_run_loop_remove_timer(&connection_timer);
                    ble_exit_pairing_mode();   // we have our device; stop accepting new ones
                    printf("HID service client connected, found %d services\n",
                        gattservice_subevent_hid_service_connected_get_num_instances(packet));

                    /* Hand the remote's HID REPORT DESCRIPTOR to core 0. This is what teaches the
                       engine what the remote's bytes MEAN -- it becomes "their descriptor", exactly
                       as a wired USB device's descriptor does. (We still present hid-remapper's OWN
                       descriptor to the PC; that is the whole point of remapping.) */
                    {
                        uint16_t dlen = hids_client_descriptor_storage_get_descriptor_len(hids_cid, 0);
                        const uint8_t * ddata = hids_client_descriptor_storage_get_descriptor_data(hids_cid, 0);
                        if ((ddata != NULL) && (dlen > 0)) {
                            printf("HID report descriptor: %u bytes -> engine\n", dlen);
                            ble_bridge_set_descriptor(ddata, dlen);
                        } else {
                            printf("!! no HID report descriptor from the device (len=%u)\n", dlen);
                        }
                    }

                                        // store device as bonded
                    if (btstack_tlv_singleton_impl){
                        btstack_tlv_singleton_impl->store_tag(btstack_tlv_singleton_context, TLV_TAG_HOGD, (const uint8_t *) &remote_device, sizeof(remote_device));
                    }
                    // done
                    printf("Ready - please start typing or mousing..\n");
                    app_state = READY;
                    break;
                default:
                    printf("HID service client connection failed, status 0x%02x.\n", status);
                    handle_outgoing_connection_error();
                    break;
            }
            break;

        case GATTSERVICE_SUBEVENT_HID_SERVICE_DISCONNECTED:
            printf("HID service client disconnected\n");
            hog_start_connect();
            break;

        case GATTSERVICE_SUBEVENT_HID_REPORT:
            hid_handle_input_report(
                gattservice_subevent_hid_report_get_service_index(packet),
                gattservice_subevent_hid_report_get_report(packet), 
                gattservice_subevent_hid_report_get_report_len(packet));
            break;

        default:
            break;
    }
}

/* LISTING_START(packetHandler): Packet Handler */
static void packet_handler (uint8_t packet_type, uint16_t channel, uint8_t *packet, uint16_t size){
    /* LISTING_PAUSE */
    UNUSED(channel);
    UNUSED(size);
    uint8_t event;
    /* LISTING_RESUME */
    switch (packet_type) {
        case HCI_EVENT_PACKET:
            event = hci_event_packet_get_type(packet);
            switch (event) {
                case BTSTACK_EVENT_STATE:
                    if (btstack_event_state_get_state(packet) != HCI_STATE_WORKING) break;
                    btstack_assert(app_state == W4_WORKING);
                    
                    hog_start_connect();
                    break;
                case GAP_EVENT_ADVERTISING_REPORT:
                    if (app_state != W4_HID_DEVICE_FOUND) break;
                    {
                        bd_addr_t _a;
                        gap_event_advertising_report_get_address(packet, _a);
                        bool has_hid = adv_event_contains_hid_service(packet);

                        // Log the advertised NAME as well as the address. Without it every device is
                        // an anonymous MAC and you cannot tell which one is yours -- and the HID
                        // flag is useless for picking: on a real desk, 6 of 7 devices advertise
                        // hid=0 (including remotes that ARE HID devices), and the one that sets it
                        // may be a stranger's keyboard.
                        char name[32] = "";
                        adv_event_get_name(packet, name, sizeof(name));
                        printf("Adv %s  hid=%d  rssi=%d  name=\"%s\"\n",
                               bd_addr_to_str(_a), (int) has_hid,
                               (int) (int8_t) gap_event_advertising_report_get_rssi(packet), name);

                        // WHICH DEVICE DO WE CONNECT TO?
                        //   * If a target address is set, ONLY that device. (This is the general
                        //     mechanism: the web tool will set it after you pick from a scan list.
                        //     It is not tied to any one product.)
                        //   * Otherwise fall back to "advertises the HID UUID", which is what the
                        //     BTstack example does -- and which misses most real devices.
                        if (ble_has_target_addr()) {
                            if (!ble_addr_matches_target(_a)) break;
                            printf("Target matched.\n");
                        } else if (!has_hid) {
                            break;
                        }
                    }
                    // stop scan
                    gap_stop_scan();
                    // store remote device address and type
                    gap_event_advertising_report_get_address(packet, remote_device.addr);
                    remote_device.addr_type = gap_event_advertising_report_get_address_type(packet);
                    // connect
                    printf("Found, connect to device with %s address %s ...\n", remote_device.addr_type == 0 ? "public" : "random" , bd_addr_to_str(remote_device.addr));
                    hog_connect();
                    break;
                case HCI_EVENT_DISCONNECTION_COMPLETE: {
                    // BUG (fixed): this used to `break` unless app_state == READY, which made the
                    // `default:` arm below dead code. A link that dropped while CONNECTING or
                    // during HID DISCOVERY was therefore silently ignored -- the firmware sat
                    // there fast-blinking forever with a stale connection handle. Handle it in
                    // every state.
                    uint8_t reason = hci_event_disconnection_complete_get_reason(packet);
                    // 0x08 = supervision timeout (link lost / out of range / device slept)
                    // 0x13 = remote terminated   0x16 = local terminated   0x3e = failed to establish
                    printf("\nDisconnected (reason 0x%02x)", reason);
                    connection_handle = HCI_CON_HANDLE_INVALID;
                    switch (app_state){
                        case READY:
                            printf(" - reconnecting...\n");
                            app_state = W4_TIMEOUT_THEN_RECONNECT;
                            break;
                        default:
                            printf(" while %s - starting over...\n",
                                   app_state == W4_HID_CLIENT_CONNECTED ? "discovering the HID service"
                                 : app_state == W4_ENCRYPTED             ? "pairing"
                                 : app_state == W4_CONNECTED             ? "connecting"
                                                                         : "scanning");
                            app_state = W4_TIMEOUT_THEN_SCAN;
                            break;
                    }
                    // set timer (remove first: a scan/connection timeout may still be queued,
                    // and btstack_run_loop_add_timer asserts on an already-queued timer)
                    btstack_run_loop_remove_timer(&connection_timer);
                    btstack_run_loop_set_timer(&connection_timer, 100);
                    btstack_run_loop_set_timer_handler(&connection_timer, &hog_reconnect_timeout);
                    btstack_run_loop_add_timer(&connection_timer);
                    break;
                }
                case HCI_EVENT_META_GAP:
                    // wait for connection complete
                    if (hci_event_gap_meta_get_subevent_code(packet) != GAP_SUBEVENT_LE_CONNECTION_COMPLETE) break;
                    if (app_state != W4_CONNECTED) return;
                    btstack_run_loop_remove_timer(&connection_timer);
                    connection_handle = gap_subevent_le_connection_complete_get_connection_handle(packet);
                    // request security
                    app_state = W4_ENCRYPTED;
                    sm_request_pairing(connection_handle);
                    break;
                default:
                    break;
            }
            break;
        default:
            break;
    }
}
