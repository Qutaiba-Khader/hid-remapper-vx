/* @section HCI packet handler
 *
 * @text The SM packet handler receives Security Manager Events required for pairing.
 * It also receives events generated during Identity Resolving
 * see Listing SMPacketHandler.
 */

/* LISTING_START(SMPacketHandler): Scanning and receiving advertisements */

static void sm_packet_handler(uint8_t packet_type, uint16_t channel, uint8_t *packet, uint16_t size){
    UNUSED(channel);
    UNUSED(size);

    if (packet_type != HCI_EVENT_PACKET) return;

    bool connect_to_service = false;

    switch (hci_event_packet_get_type(packet)) {
        case SM_EVENT_JUST_WORKS_REQUEST:
            printf("Just works requested\n");
            sm_just_works_confirm(sm_event_just_works_request_get_handle(packet));
            break;
        case SM_EVENT_NUMERIC_COMPARISON_REQUEST:
            printf("Confirming numeric comparison: %"PRIu32"\n", sm_event_numeric_comparison_request_get_passkey(packet));
            sm_numeric_comparison_confirm(sm_event_passkey_display_number_get_handle(packet));
            break;
        case SM_EVENT_PASSKEY_DISPLAY_NUMBER:
            printf("Display Passkey: %"PRIu32"\n", sm_event_passkey_display_number_get_passkey(packet));
            break;
        case SM_EVENT_PAIRING_COMPLETE:
            switch (sm_event_pairing_complete_get_status(packet)){
                case ERROR_CODE_SUCCESS:
                    printf("Pairing complete, success\n");
                    connect_to_service = true;
                    break;
                case ERROR_CODE_CONNECTION_TIMEOUT:
                    printf("Pairing failed, timeout\n");
                    break;
                case ERROR_CODE_REMOTE_USER_TERMINATED_CONNECTION:
                    printf("Pairing failed, disconnected\n");
                    break;
                case ERROR_CODE_AUTHENTICATION_FAILURE:
                    printf("Pairing failed, reason = %u\n", sm_event_pairing_complete_get_reason(packet));
                    break;
                default:
                    break;
            }
            break;
        case SM_EVENT_REENCRYPTION_COMPLETE:
            printf("Re-encryption complete, success\n");
            connect_to_service = true;
            break;
        default:
            break;
    }

    if (connect_to_service){
        // continue - query primary services
        printf("Search for HID service.\n");
        app_state = W4_HID_CLIENT_CONNECTED;
        // NEVER ignore this status. It used to be discarded, so when the call failed we printed
        // "Search for HID service." and hung forever with no clue why. It fails with
        // BTSTACK_MEMORY_ALLOC_FAILED when MAX_NR_HIDS_CLIENTS is not defined in btstack_config.h.
        uint8_t status = hids_client_connect(connection_handle, handle_gatt_client_event, protocol_mode, &hids_cid);
        if (status != ERROR_CODE_SUCCESS){
            // 0x56 = BTSTACK_MEMORY_ALLOC_FAILED -> the HIDS client pool is empty, i.e.
            // MAX_NR_HIDS_CLIENTS is missing from btstack_config.h.
            printf("!! hids_client_connect FAILED, status = 0x%02x (0x56 = out of memory: check MAX_NR_HIDS_CLIENTS)\n", status);
            app_state = W4_HID_DEVICE_FOUND;
            gap_disconnect(connection_handle);
        } else {
            printf("hids_client_connect OK, discovering HID service (timeout %dms)...\n", HID_DISCOVERY_TIMEOUT_MS);
            // Arm the deadline. Without it, a peer that accepts the link but ignores GATT leaves
            // us fast-blinking in silence forever -- there is nothing else in this state to
            // print, so the firmware just looks dead.
            btstack_run_loop_remove_timer(&connection_timer);
            btstack_run_loop_set_timer(&connection_timer, HID_DISCOVERY_TIMEOUT_MS);
            btstack_run_loop_set_timer_handler(&connection_timer, &hog_discovery_timeout);
            btstack_run_loop_add_timer(&connection_timer);
        }
    }
}
