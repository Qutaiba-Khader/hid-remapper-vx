// RGB LED output — real hardware colors on HID page 0xFFFA (low 16 bits =
// RGB565 color, matching firmware/src/remapper.h). hex = the actual color
// shown by the onboard WS2812 LED, computed via standard 5/6/5 -> 8/8/8 bit
// expansion; "LED Off" (0xfffa0000) = no light (null).
const LED_HEX = {
  "0xfffa0000": null,
  "0xfffaf800": "#ff0000",
  "0xfffafc00": "#ff8200",
  "0xfffafe00": "#ffc300",
  "0xfffaffe0": "#ffff00",
  "0xfffaa7e0": "#a5ff00",
  "0xfffa07e0": "#00ff00",
  "0xfffa07f0": "#00ff84",
  "0xfffa07ff": "#00ffff",
  "0xfffa041f": "#0082ff",
  "0xfffa001f": "#0000ff",
  "0xfffa401f": "#4200ff",
  "0xfffa801f": "#8400ff",
  "0xfffaf81f": "#ff00ff",
  "0xfffaf810": "#ff0084",
  "0xfffaffff": "#ffffff",
};
function isLed(code) { return !!code && code.indexOf("0xfffa") === 0; }
function ledColor(code) { return LED_HEX[code] || null; }

// Flat lookup: code -> { name, categoryId, accent, label }
const USAGE_BY_CODE = (() => {
  const map = {};
  USAGE_CATEGORIES.forEach((cat) => {
    cat.usages.forEach(([code, name]) => {
      if (!map[code]) map[code] = { name, categoryId: cat.id, accent: cat.accent, label: cat.label };
    });
  });
  return map;
})();

function usageName(code) {
  if (!code || code === "0x00000000") return "Unmapped";
  // The firmware reports each combo's internal state on page 0xFFFB so the Monitor can show
  // whether a combo actually latched. Those slots are generated, not in the catalog.
  const n = parseInt(code, 16) >>> 0;
  if (Number.isFinite(n) && ((n & 0xffff0000) >>> 0) === 0xfffb0000) return "Combo " + (n & 0xffff);
  return (USAGE_BY_CODE[code] && USAGE_BY_CODE[code].name) || code;
}
function usageAccent(code) {
  if (isLed(code)) return ledColor(code) || "#8a90b0";
  return (USAGE_BY_CODE[code] && USAGE_BY_CODE[code].accent) || "#a1a8c3";
}
function usageCategoryLabel(code) {
  return (USAGE_BY_CODE[code] && USAGE_BY_CODE[code].label) || "Custom";
}

window.HRX_USAGES = { USAGE_CATEGORIES, USAGE_BY_CODE, usageName, usageAccent, usageCategoryLabel, isLed, ledColor, LED_HEX };

