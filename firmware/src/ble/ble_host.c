void ble_host_init(void){
    // Build-time target, e.g. -DBLE_TARGET_ADDR="68:FC:CA:B4:43:B7".
    // At runtime the web tool will call ble_host_set_target_addr() with whatever device you
    // picked from the scan list -- this define just lets us test without the UI in place.
#ifdef BLE_TARGET_ADDR
    ble_host_set_target_addr(BLE_TARGET_ADDR);
#endif


    if (cyw43_arch_init()) { printf("cyw43_arch_init failed\n"); return; }
    printf("init: cyw43 ok\n"); sleep_ms(60);

    /* LISTING_START(HogBootHostSetup): HID-over-GATT Host Setup */

    l2cap_init();
    printf("init: l2cap\n"); sleep_ms(60);

    // setup SM: Display only
    sm_init();
    sm_set_io_capabilities(IO_CAPABILITY_DISPLAY_ONLY);
    sm_set_authentication_requirements(SM_AUTHREQ_SECURE_CONNECTION | SM_AUTHREQ_BONDING);
    printf("init: sm\n"); sleep_ms(60);

    //
    gatt_client_init();
    printf("init: gatt_client\n"); sleep_ms(60);

    // setup ATT server - only needed if LE Peripheral does ATT queries on its own, e.g. Android and iOS
    att_server_init(profile_data, NULL, NULL);
    printf("init: att_server\n"); sleep_ms(60);

    hids_client_init(hid_descriptor_storage, sizeof(hid_descriptor_storage));
    printf("init: hids_client\n"); sleep_ms(60);

    // -DBLE_CLEAR_BONDS=ON -> forget every bond at boot, so we PAIR FRESH instead of
    // re-encrypting a bond the peer may no longer honour. The hardware log showed
    // "Re-encryption complete, success" and then HID discovery hanging forever -- a stale bond
    // is the prime suspect for a peer that accepts the link but will not serve its GATT db.
#ifdef BLE_CLEAR_BONDS
    {
        int deleted = 0;
        int max = le_device_db_max_count();
        for (int i = 0; i < max; i++){
            int addr_type = BD_ADDR_TYPE_UNKNOWN;
            bd_addr_t addr;
            sm_key_t irk;
            le_device_db_info(i, &addr_type, addr, irk);
            if (addr_type == BD_ADDR_TYPE_UNKNOWN) continue;
            le_device_db_remove(i);
            deleted++;
        }
        // also drop the "last connected device" tag so we do not try to reconnect to it
        btstack_tlv_get_instance(&btstack_tlv_singleton_impl, &btstack_tlv_singleton_context);
        if (btstack_tlv_singleton_impl){
            btstack_tlv_singleton_impl->delete_tag(btstack_tlv_singleton_context, TLV_TAG_HOGD);
        }
        printf("init: BONDS CLEARED (%d) -- will pair fresh\n", deleted); sleep_ms(60);
    }
#endif

    // register for events from HCI
    hci_event_callback_registration.callback = &packet_handler;
    hci_add_event_handler(&hci_event_callback_registration);

    // register for events from Security Manager
    sm_event_callback_registration.callback = &sm_packet_handler;
    sm_add_event_handler(&sm_event_callback_registration);

    // DO NOT call sm_set_authentication_requirements() again here.
    //
    // This second call USED TO BE HERE, and it silently overwrote the one above -- dropping
    // SM_AUTHREQ_SECURE_CONNECTION and leaving only SM_AUTHREQ_BONDING. The result: we paired
    // with LEGACY, unauthenticated Just Works. Pairing "succeeded"... and then the remote
    // refused to serve its HID characteristics, because they require a properly secured link.
    // The peer accepted the connection and ignored every GATT request, so HID discovery went
    // silent and the LED blinked forever with nothing in the log.
    //
    // The upstream example this file came from has this line commented out. We did not.
    // (shiomachisoft/picow_ble_usb_hid_bridge keeps it commented, and it works.)
    // The correct requirements are set once, above:
    //     sm_set_authentication_requirements(SM_AUTHREQ_SECURE_CONNECTION | SM_AUTHREQ_BONDING);
    printf("init: handlers\n"); sleep_ms(60);

    /* LISTING_END */

    // Disable stdout buffering
	setvbuf(stdin, NULL, _IONBF, 0);

    app_state = W4_WORKING;

    // onboard LED status (Adapt E): reflects app_state going forward.
    btstack_run_loop_set_timer_handler(&led_timer, &led_timer_handler);
    btstack_run_loop_set_timer(&led_timer, 100);
    btstack_run_loop_add_timer(&led_timer);
    printf("init: led timer\n"); sleep_ms(60);

    // Turn on the device
    hci_power_control(HCI_POWER_ON);
    printf("init: hci_power_on -> entering run loop\n"); sleep_ms(60);
}

void ble_host_run(void) {
    btstack_run_loop_execute();
}

/* CORE 1 entry point. btstack_run_loop_execute() never returns -- which is exactly why BTstack gets
   a core to itself, leaving core 0 free to run hid-remapper's engine and the USB device stack.
   (shiomachisoft/picow_ble_usb_hid_bridge does the same, and it is proven on this hardware.) */
void ble_host_main(void) {
    // Let core 0 freeze us while it erases flash to save the config -- we execute FROM flash, so
    // without this we would be fetching instructions from a chip that has stopped answering.
    multicore_lockout_victim_init();

    ble_host_init();
    ble_host_run();
}

