/* PAIRING MODE.
 *
 * Off by default. While off, the remapper ONLY reconnects to the device it already knows, and will
 * not bond with anything else -- so an absent remote does not leave it open to the whole room.
 *
 * The config tool's "Pair new device" button opens a WINDOW: for PAIRING_WINDOW_MS we scan and will
 * accept a new device. The window closes as soon as one is paired, or when it times out -- it never
 * stays open. */
#define PAIRING_WINDOW_MS 180000   // 3 minutes: long enough to go and wake the remote

static bool pairing_mode = false;
static btstack_timer_source_t pairing_timer;

static void pairing_window_expired(btstack_timer_source_t * ts){
    UNUSED(ts);
    if (!pairing_mode) return;
    pairing_mode = false;
    printf("\nPairing window closed (nothing paired). Not pairable again until you ask.\n");
    gap_stop_scan();
    hog_start_connect();   // fall back to the remembered device, or go idle
}

static void ble_enter_pairing_mode(void){
    pairing_mode = true;
    printf("PAIRING MODE OPEN for %d s -- the next BLE HID device found will be paired.\n",
           PAIRING_WINDOW_MS / 1000);
    btstack_run_loop_remove_timer(&pairing_timer);
    btstack_run_loop_set_timer(&pairing_timer, PAIRING_WINDOW_MS);
    btstack_run_loop_set_timer_handler(&pairing_timer, &pairing_window_expired);
    btstack_run_loop_add_timer(&pairing_timer);
}

static void ble_exit_pairing_mode(void){
    if (!pairing_mode) return;
    pairing_mode = false;
    btstack_run_loop_remove_timer(&pairing_timer);
    printf("Paired. Pairing mode closed.\n");
}

/* The config tool's "Pair new device" / "Clear bonds" buttons land on CORE 0 as config commands
   12/13. BTstack may only be touched from core 1, so core 0 raises a flag in the bridge and we
   pick it up here, inside BTstack's own run loop. Polled from the LED timer, which already ticks
   every 100ms -- no extra timer, and a 100ms latency on a button press is invisible. */
static void ble_handle_core0_requests(void){
    uint32_t req = ble_bridge_take_requests();
    if (req == 0) return;

    if (req & BLE_REQ_CLEAR_BONDS){
        printf("\n== CLEAR BONDS (from the config tool) ==\n");
        ble_clear_all_bonds();
    }
    if (req & BLE_REQ_PAIR_NEW){
        printf("\n== PAIR NEW DEVICE (from the config tool) ==\n");
        // Forget the device we are on, so we stop reconnecting to it and go looking again.
        if (target_addr_set) {
            target_addr_set = false;   // a new pairing should not be pinned to the old address
        }
        ble_clear_all_bonds();
    }

    // Drop the link and start over. The disconnect handler restarts the scan; if we were not
    // connected, start it here.
    if (connection_handle != HCI_CON_HANDLE_INVALID){
        app_state = W4_TIMEOUT_THEN_SCAN;
        gap_disconnect(connection_handle);
    } else {
        hog_start_connect();   // NOT _scan: that would make us pairable again
    }
}

static btstack_timer_source_t led_timer;
static void led_timer_handler(btstack_timer_source_t * ts){
    static uint32_t tick = 0;
    tick++;

    ble_handle_core0_requests();

    /* THE LED IS THE ONLY STATUS CHANNEL ON THIS BUILD (no USB serial -- we are a HID device), so
       every state MUST look different. It used to lump "idle, not pairable" and "scanning for your
       remote" into the same slow blink, which made it impossible to tell whether a pairing request
       had even arrived. */
    int on;
    switch (app_state){
        case READY:
            on = 1;                              // SOLID           = connected, reports flowing
            break;
        case W4_CONNECTED:
        case W4_ENCRYPTED:
        case W4_HID_CLIENT_CONNECTED:
            on = tick & 1;                       // FAST BLINK      = connecting / pairing
            break;
        case W4_HID_DEVICE_FOUND:
            // DOUBLE BLINK ("blink-blink ... pause") = PAIRING WINDOW OPEN, actively looking.
            // Unmistakable, and it tells you the button press really did land.
            on = ((tick % 10) == 0) || ((tick % 10) == 2);
            break;
        default:
            // SLOW BLINK = idle / retrying a bonded remote that is not answering (switched off,
            // out of range). Not an error, and NOT a state where we would pair with anything else.
            on = (tick / 5) & 1;
            break;
    }
    cyw43_arch_gpio_put(CYW43_WL_GPIO_LED_PIN, on);
    btstack_run_loop_set_timer(ts, 100);
    btstack_run_loop_add_timer(ts);
}

